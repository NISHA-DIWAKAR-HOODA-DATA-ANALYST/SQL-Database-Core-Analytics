SELECT STUDENTS.GRADE,STUDENTS.NAME,STUDENTS.TOTAL_MARKS,
CHILDREN.NAME AS NAME,CHILDREN.CITY ,CHILDREN.MARKS 
FROM STUDENTS LEFT JOIN CHILDREN ON
STUDENTS.GRADE=CHILDREN.GRADE;

SELECT STUDENTS.GRADE,STUDENTS.NAME,CHILDREN.NAME 
FROM STUDENTS
INNER JOIN CHILDREN
ON STUDENTS.GRADE=CHILDREN.GRADE;

SELECT STUDENTS.GRADE,STUDENTS.NAME,STUDENTS.TOTAL_MARKS,
CHILDREN.NAME AS NAME,CHILDREN.CITY ,CHILDREN.MARKS 
FROM STUDENTS RIGHT JOIN CHILDREN ON 
STUDENTS.GRADE=CHILDREN.GRADE;

SELECT STUDENTS.GRADE,STUDENTS.NAME,STUDENTS.TOTAL_MARKS,
STUDENTS.RESULT,CHILDREN.NAME AS NAME,
CHILDREN.CITY ,CHILDREN.MARKS 
FROM STUDENTS FULL OUTER JOIN CHILDREN ON 
STUDENTS.GRADE=CHILDREN.GRADE;

